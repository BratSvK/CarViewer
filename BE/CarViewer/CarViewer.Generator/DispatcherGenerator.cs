using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CarViewer.Generator;

[Generator]
public class DispatcherGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ISymbol?> queryHandlers = context.SyntaxProvider
            .CreateSyntaxProvider(
                (s, _) => s is ClassDeclarationSyntax c
                          && c.BaseList?.Types.Any(t =>
                              t.Type is GenericNameSyntax
                              {
                                  Identifier: { ValueText: "IQueryHandler" }
                              }) == true,
                (ctx, _) =>
                {
                    var syntax = (ClassDeclarationSyntax)ctx.Node;
                    var symbol = ctx.SemanticModel.GetDeclaredSymbol(syntax);

                    return symbol;
                })
            .Where(m => m is not null);
        
        IncrementalValuesProvider<ISymbol?> commandHandlers = context.SyntaxProvider
            .CreateSyntaxProvider(
                (s, _) => s is ClassDeclarationSyntax c
                          && c.BaseList?.Types.Any(t =>
                              t.Type is GenericNameSyntax
                              {
                                  Identifier: { ValueText: "ICommandHandler" }
                              }) == true,
                (ctx, _) =>
                {
                    var syntax = (ClassDeclarationSyntax)ctx.Node;
                    var symbol = ctx.SemanticModel.GetDeclaredSymbol(syntax);
                    
                    return symbol;
                })
            .Where(m => m is not null);
        
        var compilation = context.CompilationProvider
            .Combine(queryHandlers.Collect())
            .Combine(commandHandlers.Collect());

        context.RegisterSourceOutput(compilation, (spc, source) =>
        {
            var generatorText = $@"// <auto-generated>
using System;
using CarViewer.Application.Mediator.Commands;
using CarViewer.Application.Mediator.Queries;
using Microsoft.Extensions.DependencyInjection;

namespace CarViewer.Application.Mediator;

public class Dispatcher : IDispatcher
{{
    private readonly IServiceProvider _serviceProvider;

    public Dispatcher(IServiceProvider serviceProvider)
    {{
        _serviceProvider = serviceProvider;
    }}

    public async Task<T> QueryAsync<T>(IQuery<T> query, CancellationToken cancellationToken = default)
    {{
        var queryType = query.GetType();
        
        switch(queryType.Name)
        {{
        {GenerateQueryCases(source.Left.Right)}
            default:
                throw new ArgumentException($""No handler found for query type {{queryType.Name}}"");
        }}
    }}

    public async Task<T> SendAsync<T>(ICommand<T> command, CancellationToken cancellationToken = default)
    {{
        var commandType = command.GetType();
        
        switch(commandType.Name)
        {{
        {GenerateCommandCases(source.Right)}
            default:
                throw new ArgumentException($""No handler found for command type {{commandType.Name}}"");
        }}
    }}
}}";

            spc.AddSource("Dispatcher.generated.cs", generatorText);
        });
    }
    
    private static string GenerateQueryCases(IEnumerable<ISymbol> handlers)
    {
        var cases = new StringBuilder();

        foreach (INamedTypeSymbol? handler in handlers.OfType<INamedTypeSymbol>())
        {
            ImmutableArray<INamedTypeSymbol> interfaces = handler.AllInterfaces;

            foreach (var @interface in interfaces)
            {
                if (!@interface.Name.Equals("IQueryHandler", StringComparison.Ordinal)) continue;

                ITypeSymbol queryType = @interface.TypeArguments[0];
                ITypeSymbol resultType = @interface.TypeArguments[1];

                cases.AppendLine($@"
                case nameof({queryType}):
                {{
                    var handler = _serviceProvider.GetRequiredService<IQueryHandler<{queryType}, {resultType}>>();
                    {queryType} q = ({queryType})query;
                    var result = await handler.HandleAsync(q!, cancellationToken);
                    return (T)(object)result!;
                }}");
            }
        }

        return cases.ToString();
    }
    
    private static string GenerateCommandCases(IEnumerable<ISymbol> handlers)
    {
        var cases = new StringBuilder();

        foreach (var handler in handlers.OfType<INamedTypeSymbol>())
        {
            ImmutableArray<INamedTypeSymbol> interfaces = handler.AllInterfaces;
            
            foreach(INamedTypeSymbol? @interface in interfaces)
            {
                if (!@interface.Name.Equals("ICommandHandler", StringComparison.Ordinal) || @interface.TypeArguments.Length != 2) continue;
                
                ITypeSymbol commandType = @interface.TypeArguments[0];
                ITypeSymbol resultType = @interface.TypeArguments[1];
                
                cases.AppendLine($@"
                case nameof({commandType}):
                {{
                    var handler = _serviceProvider.GetRequiredService<ICommandHandler<{commandType}, {resultType}>>();
                    {commandType} c = ({commandType})command;
                    var result = await handler.HandleAsync(c!, cancellationToken);
                    return (T)(object)result!;
                }}");
            }
        }

        return cases.ToString();
    }
}