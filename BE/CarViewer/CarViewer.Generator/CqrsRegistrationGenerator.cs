using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CarViewer.Generator;

[Generator]
public class CqrsRegistrationGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Step 1: Discover all classes implementing ICommandHandler or IQueryHandler
        var commandHandlers = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => IsCommandHandler(node),
                transform: static (context, _) =>
                {
                    var classDeclaration = (ClassDeclarationSyntax)context.Node;
                    var symbol = context.SemanticModel.GetDeclaredSymbol(classDeclaration);
                    return symbol;
                })
            .Where(static symbol => symbol is not null);

        var queryHandlers = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => IsQueryHandler(node),
                transform: static (context, _) =>
                {
                    var classDeclaration = (ClassDeclarationSyntax)context.Node;
                    var symbol = context.SemanticModel.GetDeclaredSymbol(classDeclaration);
                    return symbol;
                })
            .Where(static symbol => symbol is not null);

        // Step 2: Combine all handlers
        var collectedHandlers = commandHandlers.Collect().Combine(queryHandlers.Collect());

        // Step 3: Generate code
        context.RegisterSourceOutput(collectedHandlers, (spc, handlers) =>
        {
            var (commandHandlerSymbols, queryHandlerSymbols) = handlers;

            // Append service registrations
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Generated by CarViewer.SourceGenerator");
            sb.AppendLine();
            sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
            sb.AppendLine();
            sb.AppendLine("namespace CarViewer.Application.Mediator;");
            sb.AppendLine("public static class ApplicationServiceCollectionExtensions");
            sb.AppendLine("{");
            sb.AppendLine("    public static IServiceCollection AddMediator(this IServiceCollection services)");
            sb.AppendLine("    {");

            foreach (var commandHandler in commandHandlerSymbols.Distinct(SymbolEqualityComparer.Default))
            {
                GenerateRegistration(sb, commandHandler, "ICommandHandler");
            }

            foreach (var queryHandler in queryHandlerSymbols.Distinct(SymbolEqualityComparer.Default))
            {
                GenerateRegistration(sb, queryHandler, "IQueryHandler");
            }

            sb.AppendLine("        services.AddTransient<CarViewer.Application.Mediator.IDispatcher, CarViewer.Application.Mediator.Dispatcher>();");
            sb.AppendLine("        return services;");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            // Output the generated source code
            spc.AddSource("CqrsRegistrationGenerator.generated.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        });
    }

    private static void GenerateRegistration(StringBuilder sb, ISymbol handlerSymbol, string interfaceName)
    {

        if (handlerSymbol is not INamedTypeSymbol namedType) return;

        foreach (var implementedInterface in namedType.Interfaces)
        {
            if (implementedInterface.Name == interfaceName)
            {
                sb.AppendLine($"        services.AddScoped<{implementedInterface.ToDisplayString()}, {namedType.ToDisplayString()}>();");
            }
        }
    }

    private static bool IsCommandHandler(SyntaxNode node)
    {
        // Checks if a class implements ICommandHandler<> or ICommandHandler<,>
        return node is ClassDeclarationSyntax c &&
               c.BaseList?.Types.Any(t =>
                   t.Type is GenericNameSyntax { Identifier.Text: "ICommandHandler" }) == true;
    }

    private static bool IsQueryHandler(SyntaxNode node)
    {
        // Checks if a class implements IQueryHandler<,>
        return node is ClassDeclarationSyntax c &&
               c.BaseList?.Types.Any(t =>
                   t.Type is GenericNameSyntax { Identifier.Text: "IQueryHandler" }) == true;
    }
}